// Generate browser/icons.ts: Lucide shapes as SVG strings for the plain-TS pages, without
// bundling React. Add a name here, then run `bun run build:ui`.
import { writeFile } from "node:fs/promises";
const NAMES = [
  "inbox",
  "book-open",
  "settings",
  "lightbulb",
  "cog",
  "telescope",
  "book-bookmark",
  "external-link",
  "file-text",
  "graduation-cap",
  "list-checks",
  "arrow-left",
  "pause",
  "play",
  "plug",
  "search",
  "plus",
  "check",
  "circle-alert",
  "refresh-cw",
  "copy",
  "compass",
];
const icons: Record<string, string> = {};
for (const name of NAMES) {
  const { __iconData } = await import(`lucide-react/dist/esm/icons/${name}.mjs`);
  icons[name] = (__iconData.node as [string, Record<string, string>][])
    .map(([tag, attrs]) => {
      const a = Object.entries(attrs)
        .filter(([k]) => k !== "key")
        .map(([k, v]) => `${k}="${v}"`)
        .join(" ");
      return `<${tag} ${a}/>`;
    })
    .join("");
}
await writeFile(
  "browser/icons.ts",
  `// Generated by scripts/icons.ts from lucide-react (ISC). Do not edit.
const SHAPES = ${JSON.stringify(icons, null, 2)} as const;
export type IconName = keyof typeof SHAPES;
export const icon = (name: IconName, size = 16) =>
  \`<svg class="icon" width="\${size}" height="\${size}" viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round" aria-hidden="true">\${SHAPES[name]}</svg>\`;
`,
);
// Keep the generated file in the repo's format so `fmt:check` stays clean after a build.
Bun.spawnSync(["node_modules/.bin/oxfmt", "browser/icons.ts"]);
